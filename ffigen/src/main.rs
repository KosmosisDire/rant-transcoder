//! Regenerates `transcoder/src/ffi.rs` from the pinned FFmpeg headers. With `--check` it
//! changes nothing and exits 1 when the checked in file is stale, or 77 when libclang is missing.

use std::path::{Path, PathBuf};
use std::process::ExitCode;

include!("../../transcoder/ffmpeg.rs");

const SKIPPED: u8 = 77;

/// Every header the transcoder calls into.
const HEADERS: &str = "
#include <libavcodec/avcodec.h>
#include <libavcodec/bsf.h>
#include <libavfilter/avfilter.h>
#include <libavfilter/buffersink.h>
#include <libavfilter/buffersrc.h>
#include <libavformat/avformat.h>
#include <libavutil/hwcontext.h>
#include <libavutil/imgutils.h>
#include <libavutil/opt.h>
#include <libavutil/pixdesc.h>
#include <libswscale/swscale.h>
";

fn main() -> ExitCode {
    let check = std::env::args().any(|a| a == "--check");
    let here = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let root = here.parent().expect("ffigen sits in the workspace");
    let target = root.join("transcoder/src/ffi.rs");
    let cache = std::env::var_os("CARGO_TARGET_DIR").map(PathBuf::from).unwrap_or_else(|| root.join("target")).join("ffmpeg");
    // the headers are the same in every platform's archive, so the host's will do
    let ffmpeg = match ffmpeg_dir(std::env::consts::OS, std::env::consts::ARCH, &cache) {
        Ok(dir) => dir,
        Err(e) => {
            eprintln!("ffigen: {e}");
            return ExitCode::FAILURE;
        }
    };
    // bindgen panics when it cannot load libclang, the one failure that skips
    let generated = match std::panic::catch_unwind(|| generate(&ffmpeg.join("include"), &here.join("include"))) {
        Ok(Ok(text)) => text,
        Ok(Err(e)) => {
            eprintln!("ffigen: bindgen failed on {}: {e}", ffmpeg.display());
            return ExitCode::FAILURE;
        }
        Err(panic) => {
            let text = panic.downcast_ref::<String>().map(String::as_str).or_else(|| panic.downcast_ref::<&str>().copied()).unwrap_or("");
            if !text.contains("libclang") {
                std::panic::resume_unwind(panic);
            }
            eprintln!("ffigen: SKIPPED, libclang could not be loaded (set LIBCLANG_PATH)");
            return ExitCode::from(SKIPPED);
        }
    };
    // a Windows checkout may hand ffi.rs back with CRLF line ends
    let current = std::fs::read_to_string(&target).unwrap_or_default().replace("\r\n", "\n");
    if check {
        if current == generated {
            println!("ffigen: ffi.rs matches {}", ffmpeg.display());
            return ExitCode::SUCCESS;
        }
        eprintln!("ffigen: ffi.rs is stale, run `cargo run -p rant-transcoder-ffigen`");
        return ExitCode::FAILURE;
    }
    if current != generated {
        std::fs::write(&target, generated).expect("ffigen: cannot write ffi.rs");
        println!("ffigen: wrote {}", target.display());
    } else {
        println!("ffigen: ffi.rs is current");
    }
    ExitCode::SUCCESS
}

fn generate(include: &Path, stubs: &Path) -> Result<String, bindgen::BindgenError> {
    let target = bindgen::RustTarget::stable(85, 0).expect("ffigen: Rust 1.85 is a known target");
    let bindings = bindgen::Builder::default()
        .header_contents("ffmpeg.h", HEADERS)
        // One canonical target, so every host writes the same file. Fields typed long take
        // c_long, which Rust sizes for each target, so the layouts hold on Windows too.
        .clang_arg("--target=x86_64-unknown-linux-gnu")
        .clang_arg("-ffreestanding")
        .clang_arg("-std=c11")
        .clang_arg(format!("-isystem{}", stubs.display()))
        .clang_arg(format!("-I{}", include.display()))
        .allowlist_function("(av|avcodec|avfilter|avformat|avio|avutil|sws|swscale)_.*")
        .allowlist_var("(AV|FF|SWS)_.*|LIB(AV|SW)[A-Z]+_VERSION_(MAJOR|MINOR|MICRO)")
        // the flags sws_getContext takes as an int, which no function names
        .allowlist_type("SwsFlags")
        // va_list is spelled differently on every target, and FILE belongs to the C runtime
        .blocklist_function("av_vlog|av_log_set_callback|av_log_default_callback|av_log_format_line2?|av_vbprintf|avio_vprintf")
        .blocklist_function("av_hex_dump|av_pkt_dump2|avcodec_string")
        .blocklist_type("va_list|__builtin_va_list|__va_list_tag")
        .default_enum_style(bindgen::EnumVariation::Consts)
        .prepend_enum_name(false)
        .layout_tests(false)
        .derive_default(true)
        .derive_debug(false)
        .generate_comments(false)
        .merge_extern_blocks(true)
        .rust_target(target)
        .rust_edition(bindgen::RustEdition::Edition2024)
        .formatter(bindgen::Formatter::Prettyplease)
        .raw_line("// Generated by ffigen from the pinned FFmpeg headers. Run `cargo run -p rant-transcoder-ffigen` after a pin change.")
        .generate()?;
    // bindgen writes CRLF around its header lines on Windows
    Ok(bindings.to_string().replace("\r\n", "\n"))
}
